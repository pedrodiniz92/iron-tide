let LANG = "en";
try {
  const saved = localStorage.getItem("it25_lang");
  if (saved === "pt" || saved === "en") LANG = saved;
  else if ((navigator.language || "").toLowerCase().startsWith("pt")) LANG = "pt";
} catch (e) { /* private mode */ }

function t(key, params) {
  let s = (I18N[LANG] && I18N[LANG][key]) || key;
  if (params) {
    Object.keys(params).forEach((k) => {
      s = s.split("{" + k + "}").join(params[k]);
    });
  }
  return s;
}

function applyI18nStatic() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
  if (typeof updateDashHint === "function") updateDashHint();
  if (typeof refreshAudioButtons === "function") refreshAudioButtons();
}

function setLang(l) {
  LANG = l;
  try { localStorage.setItem("it25_lang", l); } catch (e) { /* private mode */ }
  applyI18nStatic();
  updateLangButton();
}

function updateLangButton() {
  const btn = document.getElementById("langButton");
  if (!btn) return;
  btn.innerHTML = "<b" + (LANG === "en" ? "" : ' style="opacity:0.45"') + ">EN</b> | <b" + (LANG === "pt" ? "" : ' style="opacity:0.45"') + ">PT</b>";
}

function buildLangButton() {
  const button = document.createElement("button");
  button.id = "langButton";
  button.style.cssText = "position:fixed;top:8px;right:64px;z-index:21;padding:4px 10px;font:12px monospace;background:#101820;color:#9ae6ff;border:1px solid #2c5f7a;cursor:pointer;";
  button.addEventListener("click", () => setLang(LANG === "en" ? "pt" : "en"));
  document.body.appendChild(button);
  updateLangButton();
}

buildLangButton();
applyI18nStatic();
